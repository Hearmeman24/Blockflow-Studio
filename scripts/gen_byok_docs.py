"""Generate the capability matrix, the known-limitations page and the
pricing-coverage list.

The first two are derived from ``backend/byok/catalog.py``, the third from the
catalog and the bundled price ledger (``prices/prices.json``, including its
not-priceable notes), so none of them can drift. They are written to ``docs/byok`` inside the
git-ignored private notes folder (``OUT_DIR``), which is created when needed;
they are not shipped with the repository:

    capability-matrix.md
    known-limitations.md
    pricing-coverage.md

Usage:

    uv run python scripts/gen_byok_docs.py           # rewrite the three files
    uv run python scripts/gen_byok_docs.py --check   # exit 1 if they differ or are missing

The output is deterministic: catalog order, no timestamps.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from backend.byok import price_ledger, pricing  # noqa: E402
from backend.byok.catalog import CATALOG, UNSUPPORTED_FEATURES, UNVERIFIED  # noqa: E402
from backend.byok.spec import (  # noqa: E402
    MB,
    MEDIA_KINDS,
    MODE_NAMES,
    PROVIDER_NAMES,
    PROVIDERS,
    MediaLimit,
    ModeSpec,
)

OUT_DIR = ROOT / "internal_docs" / "docs" / "byok"
MATRIX_NAME = "capability-matrix.md"
LIMITATIONS_NAME = "known-limitations.md"
COVERAGE_NAME = "pricing-coverage.md"
MATRIX_PATH = OUT_DIR / MATRIX_NAME
LIMITATIONS_PATH = OUT_DIR / LIMITATIONS_NAME
COVERAGE_PATH = OUT_DIR / COVERAGE_NAME

HEADER = "<!-- Generated by scripts/gen_byok_docs.py from backend/byok/catalog.py. Do not edit by hand. -->\n"

MATRIX_PREAMBLE = """# Capability matrix

This page lists every model in the capability ledger (`backend/byok/catalog.py`),
the providers that offer it, and the limits the app enforces for each mode
before it sends a request. It is generated by `scripts/gen_byok_docs.py`; to
change it, change the ledger and regenerate (see [extending.md](extending.md)).

Reading the tables:

- "None documented" means the provider documents no limit, so the app does not
  enforce one. Entries that mix documented and undocumented values are listed in
  [known-limitations.md](known-limitations.md).
- Sizes use decimal megabytes (1 MB = 1,000,000 bytes).
- The NSFW flag is a label set per model in the ledger. It does not mean the
  provider allows any content; provider content rules still apply, and the flag
  does not always match which models have a content setting (see
  [generation.md](generation.md)).
- A mode marked "not supported" is listed with the reason the ledger records.
"""

LIMITATIONS_PREAMBLE = """# Known limitations

The capability ledger records only values that the provider documentation
states. Where the documentation is silent, contradicts itself, or the app
chooses not to expose a feature, that is recorded here instead of being guessed.
This page is generated by `scripts/gen_byok_docs.py` from the `UNVERIFIED` and
`UNSUPPORTED_FEATURES` lists in `backend/byok/catalog.py`.

What these lists mean:

- **Unverified** items are places where the ledger picked the safest documented
  value (usually the stricter one) so a paid request does not fail for a
  preventable reason. The value may be tighter than what the provider really
  accepts. It has not been confirmed with live provider calls.
- **Not supported** items are provider features the app does not offer. They are
  not hidden settings; there is no way to turn them on.
- Provider documentation was captured on 2026-11-15. Providers change their
  APIs; recheck a limit against the provider's current documentation if a
  request is refused or behaves differently.
"""


# ---------------------------------------------------------------- formatting


def _size(n: int | None) -> str:
    if n is None:
        return "none documented"
    if n % MB == 0:
        return f"{n // MB} MB"
    return f"{n / MB:g} MB"


def _num(x: float | int) -> str:
    return f"{x:g}"


def _media_line(limit: MediaLimit) -> str:
    parts = [f"max {limit.max_count}"]
    if limit.min_count:
        parts.append(f"min {limit.min_count}")
    parts.append("formats " + (", ".join(limit.formats) if limit.formats else "none documented"))
    parts.append("size " + _size(limit.max_size_bytes))
    if limit.min_duration_s is not None or limit.max_duration_s is not None:
        lo = "?" if limit.min_duration_s is None else _num(limit.min_duration_s)
        hi = "?" if limit.max_duration_s is None else _num(limit.max_duration_s)
        parts.append(f"duration {lo}-{hi} s each")
    if limit.max_total_duration_s is not None:
        parts.append(f"total duration at most {_num(limit.max_total_duration_s)} s")
    if limit.min_total_duration_s is not None:
        parts.append(f"total duration at least {_num(limit.min_total_duration_s)} s")
    if limit.min_side_px is not None or limit.max_side_px is not None:
        lo = "?" if limit.min_side_px is None else str(limit.min_side_px)
        hi = "?" if limit.max_side_px is None else str(limit.max_side_px)
        parts.append(f"side {lo}-{hi} px")
    if limit.min_aspect is not None or limit.max_aspect is not None:
        lo = "?" if limit.min_aspect is None else _num(limit.min_aspect)
        hi = "?" if limit.max_aspect is None else _num(limit.max_aspect)
        parts.append(f"width/height ratio {lo}-{hi}")
    return f"`{limit.kind}`: " + "; ".join(parts)


def _prompt_line(spec: ModeSpec) -> str:
    p = spec.prompt
    text = {"required": "required", "optional": "optional", "none": "not accepted"}[p.requirement]
    extra = []
    if p.min_length is not None:
        extra.append(f"at least {p.min_length} characters")
    if p.max_length is not None:
        extra.append(f"at most {p.max_length} characters")
    return text + (f" ({', '.join(extra)})" if extra else "")


def _choice_line(choice) -> str:
    values = ", ".join(choice.values)
    default = "omitted unless set" if choice.default is None else f"default {choice.default}"
    return f"{values} ({default})"


def _setting_line(s) -> str:
    if s.type == "bool":
        detail = f"on/off, default {'on' if s.default else 'off'}" if s.default is not None else "on/off"
    elif s.type == "int":
        detail = f"integer {s.minimum}-{s.maximum}"
        detail += f", default {s.default}" if s.default is not None else ", default omitted"
    else:
        values = ", ".join(str(c) for c in s.choices)
        detail = f"one of {values}" + (f", default {s.default}" if s.default is not None else "")
    tag = {"content": " [provider content setting]", "variant": " [variant selector]"}.get(s.category, "")
    line = f"`{s.key}` ({s.label}): {detail}{tag}"
    if s.description:
        line += f". {s.description}"
    return line


def _mode_lines(spec: ModeSpec, indent: str = "") -> list[str]:
    ids = spec.ids
    lines: list[str] = []
    if ids is not None:
        ident = f"model `{ids.model}`"
        if ids.task_type:
            ident += f", task_type `{ids.task_type}`"
        if ids.version:
            ident += f", version `{ids.version}`"
        lines.append(f"- Provider identifier: {ident}")
    lines.append(f"- Prompt: {_prompt_line(spec)}")
    if spec.media:
        lines.append("- Accepted media:")
        for limit in spec.media:
            lines.append(f"  - {_media_line(limit)}")
    else:
        lines.append("- Accepted media: none")
    if spec.frames is not None:
        first = "required" if spec.frames.first_frame_required else "optional"
        last = "allowed" if spec.frames.last_frame_allowed else "not allowed"
        lines.append(f"- Frame roles: first frame {first}; last frame {last}")
    if spec.media:
        total = "no total limit documented" if spec.max_total_references is None else f"max {spec.max_total_references}"
        lines.append(f"- Total references: min {spec.min_total_references}, {total}")
        lines.append(f"- Mixed media kinds allowed: {'yes' if spec.mixed_media_allowed else 'no'}")
        lines.append(f"- Audio-only references allowed: {'yes' if spec.audio_only_allowed else 'no'}")
    if spec.mentions is not None:
        m = spec.mentions
        kinds = {limit.kind for limit in spec.media}
        forms = [f"{kind} `{getattr(m, kind)}`" for kind in MEDIA_KINDS if kind in kinds]
        if m.first_frame:
            forms.append(f"first frame `{m.first_frame}`")
        if m.last_frame:
            forms.append(f"last frame `{m.last_frame}`")
        source = "documented" if m.documented else "not documented; fallback form used"
        lines.append(f"- Prompt mentions ({source}): " + ", ".join(forms))
    if spec.duration is not None:
        d = spec.duration
        text = f"{d.min_s}-{d.max_s} s, default {d.default}"
        if d.auto_value is not None:
            text += f", provider auto value {d.auto_value}"
        lines.append(f"- Durations: {text}")
    if spec.resolutions is not None:
        lines.append(f"- Resolutions: {_choice_line(spec.resolutions)}")
    if spec.aspect_ratios is not None:
        lines.append(f"- Aspect ratios: {_choice_line(spec.aspect_ratios)}")
    if spec.settings:
        lines.append("- Settings:")
        for s in spec.settings:
            lines.append(f"  - {_setting_line(s)}")
    if spec.rules:
        lines.append("- Cross-field rules: " + ", ".join(f"`{r}`" for r in spec.rules))
    for note in spec.notes:
        lines.append(f"- Note: {note}")
    return [indent + line for line in lines]


def _render_mode(spec: ModeSpec) -> list[str]:
    name = MODE_NAMES.get(spec.mode, spec.mode)
    lines = [f"##### {name}", ""]
    if not spec.supported:
        reason = spec.unavailable_reason or "no reason recorded"
        lines += [f"Not supported: {reason}", ""]
        return lines
    lines += _mode_lines(spec)
    if spec.variants:
        lines.append(f"- Variants, selected by the `{spec.variant_key}` setting:")
        for value, variant in spec.variants:
            lines.append(f"  - `{value}`:")
            lines += _mode_lines(variant, indent="    ")
    lines.append("")
    return lines


def render_matrix() -> str:
    out: list[str] = [HEADER, MATRIX_PREAMBLE]
    out.append("## Summary")
    out.append("")
    out.append("| Model | Kind | NSFW label | " + " | ".join(PROVIDER_NAMES[p] for p in PROVIDERS) + " |")
    out.append("|---|---|---|" + "---|" * len(PROVIDERS))
    for model in CATALOG:
        cells = []
        for p in PROVIDERS:
            offering = model.offering(p)
            if offering is None or not offering.offered:
                cells.append("not offered")
            else:
                modes = [MODE_NAMES[m.mode] for m in offering.modes if m.supported]
                cells.append(", ".join(modes) if modes else "none")
        out.append(f"| {model.name} | {model.output} | {'yes' if model.nsfw else 'no'} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("## Models")
    out.append("")
    for model in CATALOG:
        out.append(f"### {model.name}")
        out.append("")
        out.append(f"- Model id: `{model.id}`")
        out.append(f"- Kind: {model.output}")
        out.append(f"- NSFW label: {'yes' if model.nsfw else 'no'}")
        if model.description:
            out.append(f"- Description: {model.description}")
        out.append("")
        for p in PROVIDERS:
            offering = model.offering(p)
            out.append(f"#### {PROVIDER_NAMES[p]}")
            out.append("")
            if offering is None or not offering.offered:
                reason = (offering.reason if offering and offering.reason else f"Not offered by {PROVIDER_NAMES[p]}")
                out.append(f"Not available: {reason}")
                out.append("")
                continue
            out.append("Available when a " + PROVIDER_NAMES[p] + " API key is saved.")
            out.append("")
            for spec in offering.modes:
                out += _render_mode(spec)
    return "\n".join(out).rstrip("\n") + "\n"


def render_limitations() -> str:
    out: list[str] = [HEADER, LIMITATIONS_PREAMBLE]
    out.append("## Unverified or contradictory provider behaviour")
    out.append("")
    for p in PROVIDERS:
        out.append(f"### {PROVIDER_NAMES[p]}")
        out.append("")
        items = [u for u in UNVERIFIED if u.provider == p]
        if not items:
            out.append("None recorded.")
            out.append("")
            continue
        for u in items:
            out.append(f"- **{u.model}**, `{u.field}`: {u.detail}")
        out.append("")
    unknown = [u for u in UNVERIFIED if u.provider not in PROVIDERS]
    if unknown:
        out.append("### Other")
        out.append("")
        for u in unknown:
            out.append(f"- **{u.model}**, `{u.field}` ({u.provider}): {u.detail}")
        out.append("")
    out.append("## Models without a cost estimate")
    out.append("")
    out.append("Some models and settings get no cost estimate before a run, for example models priced per token. "
               "[pricing-coverage.md](pricing-coverage.md) lists every model and the reason.")
    out.append("")
    out.append("## Provider features the app does not support")
    out.append("")
    out.append("These apply to the app as a whole, not to one provider.")
    out.append("")
    for feature in UNSUPPORTED_FEATURES:
        out.append(f"- {feature['label']} (`{feature['id']}`)")
    out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


COVERAGE_PREAMBLE = """# Pricing coverage

Which requests get a cost estimate before the run, per model, provider and
mode, priced against the price ledger bundled with this version
(`prices/prices.json`). This page is generated by `scripts/gen_byok_docs.py`
from the capability ledger and the price ledger, including its not-priceable
notes (`prices/model-map.json`). How prices are chosen and updated is in
[pricing.md](pricing.md).

Where there is no estimate, the generation block shows a "No estimate" chip
with the reason. The actual charge is always shown in the output viewer after
the run. Two cases apply to every model:

- An automatic (`-1`) duration is never estimated: the cost depends on how
  long the result is.
- When a reference video's length is unknown, the estimate is a lower bound
  (shown with "≥").
"""

_PROMPT = "a lighthouse on a cliff at dusk"
_IMAGE = {"kind": "image", "url": "https://example.test/a.png", "width": 1024, "height": 1024}
_VIDEO = {"kind": "video", "url": "https://example.test/a.mp4", "duration_s": 5}


def _coverage_cases(spec: ModeSpec) -> list[tuple[str, dict, list]]:
    """(label, params, references) for each resolution, plus input-video and
    less-restriction cases where the mode has them."""
    refs: list = []
    if spec.mode == "image_to_video":
        refs = [{**_IMAGE, "role": "first_frame"}]
    elif spec.mode in ("omni_reference_to_video", "image_to_image"):
        refs = [dict(_IMAGE)]
    base: dict = {"prompt": _PROMPT}
    if spec.duration is not None:
        base["duration"] = spec.duration.default
    values = list(spec.resolutions.values) if spec.resolutions else [None]
    cases = []
    for res in values:
        params = dict(base, **({"resolution": res} if res else {}))
        cases.append((res or "default", params, refs))
    if spec.media_limit("video") is not None and spec.mode == "omni_reference_to_video":
        for res in values:
            params = dict(base, **({"resolution": res} if res else {}))
            cases.append((f"{res or 'default'} with input video", params, refs + [dict(_VIDEO)]))
    if spec.setting("less_restriction") is not None:
        for res in values:
            params = dict(base, settings={"less_restriction": True}, **({"resolution": res} if res else {}))
            cases.append((f"{res or 'default'} less restriction", params, refs))
    return cases


def _coverage_specs(model, provider):
    offering = model.offering(provider)
    if offering is None or not offering.offered:
        return
    for spec in offering.modes:
        if not spec.supported:
            continue
        if spec.variant_key and spec.variants:
            for value, variant in spec.variants:
                yield variant, {spec.variant_key: value}, f"{spec.variant_key} {value}"
        else:
            yield spec, {}, ""


def coverage_rows(ledger: price_ledger.Ledger) -> list[dict]:
    """One row per model x provider x mode (x variant): priced cases and the
    reason code for every case without an estimate."""
    rows = []
    for model in CATALOG:
        for provider in PROVIDERS:
            for spec, variant_settings, variant_label in _coverage_specs(model, provider):
                priced, missing = [], {}
                for label, params, refs in _coverage_cases(spec):
                    if variant_settings:
                        params = dict(params, settings={**params.get("settings", {}), **variant_settings})
                    estimate, why = pricing.explain_cost(provider, model.id, spec.mode, params, refs,
                                                         price_list=ledger)
                    if estimate is not None:
                        priced.append(label)
                    else:
                        missing.setdefault(why["code"], (why["message"], []))[1].append(label)
                rows.append({"model": model.name, "model_id": model.id, "provider": provider, "mode": spec.mode,
                             "variant": variant_label, "priced": priced, "missing": missing})
    return rows


def render_coverage() -> str:
    ledger = price_ledger.load_bundled()
    rows = coverage_rows(ledger)
    out: list[str] = [HEADER.replace("backend/byok/catalog.py", "backend/byok/catalog.py and prices/prices.json"),
                      COVERAGE_PREAMBLE]
    out.append(f"Price ledger: generated {ledger.generated_at}, {len(ledger.entries)} prices.")
    out.append("")
    reasons: dict[str, str] = {}
    gaps = [r for r in rows if r["missing"]]
    out.append("## Without an estimate")
    out.append("")
    if not gaps:
        out.append("Every listed case has an estimate.")
    for r in gaps:
        variant = f" ({r['variant']})" if r["variant"] else ""
        for code, (message, labels) in r["missing"].items():
            reasons.setdefault(code, message.replace(pricing.AFTER_RUN, "").strip())
            cases = "all cases" if not r["priced"] else ", ".join(labels)
            out.append(f"- **{r['model']}**{variant}, {PROVIDER_NAMES[r['provider']]}, "
                       f"{MODE_NAMES[r['mode']]}: {cases}: `{code}`")
    out.append("")
    if reasons:
        out.append("Reasons:")
        out.append("")
        for code in sorted(reasons):
            out.append(f"- `{code}`: {reasons[code]}")
        out.append("")
    out.append("## Every model")
    out.append("")
    out.append("| Model | Provider | Mode | Estimated | No estimate |")
    out.append("| --- | --- | --- | --- | --- |")
    for r in rows:
        variant = f" ({r['variant']})" if r["variant"] else ""
        priced = ", ".join(r["priced"]) or "none"
        missing = "; ".join(f"{', '.join(labels)}: `{code}`" for code, (_, labels) in r["missing"].items()) or "none"
        out.append(f"| {r['model']}{variant} | {PROVIDER_NAMES[r['provider']]} | {MODE_NAMES[r['mode']]} | "
                   f"{priced} | {missing} |")
    out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def render_all(out_dir: Path = OUT_DIR) -> dict[Path, str]:
    out_dir = Path(out_dir)
    return {out_dir / MATRIX_NAME: render_matrix(), out_dir / LIMITATIONS_NAME: render_limitations(),
            out_dir / COVERAGE_NAME: render_coverage()}


def _shown(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def main(argv: list[str], out_dir: Path = OUT_DIR) -> int:
    check = "--check" in argv
    out_dir = Path(out_dir)
    if check and not out_dir.is_dir():
        print(f"{_shown(out_dir)} does not exist, so there is nothing to check.\n"
              "Run: uv run python scripts/gen_byok_docs.py", file=sys.stderr)
        return 1
    stale: list[str] = []
    for path, text in render_all(out_dir).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if check:
            stale.append(_shown(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {_shown(path)}")
    if stale:
        print("Out of date: " + ", ".join(stale) + "\nRun: uv run python scripts/gen_byok_docs.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
